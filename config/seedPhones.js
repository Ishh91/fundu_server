export async function ensureMasterPhonesSeeded() {
  try {
    const count = await MasterPhone.countDocuments();
    if (count < INDIAN_MARKET_PHONES_LAST_10_YEARS.length) {
      console.log(`[Seed] Seeding Indian Market Master Phones catalog (2015-2025)...`);
      for (const phone of INDIAN_MARKET_PHONES_LAST_10_YEARS) {
        await MasterPhone.findOneAndUpdate(
          { brand: phone.brand, model: phone.model },
          { $set: phone },
          { upsert: true, new: true }
        );
      }
      console.log(`[Seed] Master Phones catalog successfully populated.`);
    }
  } catch (err) {
    console.error(`[Seed] Error seeding master phones catalog:`, err.message);
  }
}
